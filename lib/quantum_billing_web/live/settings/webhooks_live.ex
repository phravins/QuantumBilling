defmodule QuantumBillingWeb.SettingsLive.Webhooks do
  @moduledoc """
  Owner-only: the URLs this business sends events to, and what happened to
  each delivery.

  A webhook sends the business's activity to a server someone typed in, so
  adding one is an owner's decision, as issuing an API key is. Both the route
  and the `on_mount` hook require an owner of the business being worked in.

  The signing secret is generated by the server and shown once, when an
  endpoint is added or its secret rotated; only its encrypted form is kept.
  """
  use QuantumBillingWeb, :live_view

  alias QuantumBilling.Webhooks
  alias QuantumBilling.Webhooks.Endpoint

  @event_descriptions %{
    "invoice.created" => "An invoice is created",
    "invoice.updated" => "An invoice is edited",
    "invoice.paid" => "A payment is recorded against an invoice",
    "invoice.e_invoice_generated" => "An IRN is registered",
    "invoice.e_invoice_failed" => "E-invoice registration fails",
    "client.created" => "A client is added",
    "client.updated" => "A client is edited",
    "e_way_bill.generated" => "An e-way bill is generated",
    "e_way_bill.cancelled" => "An e-way bill is cancelled",
    "credit_note.created" => "A credit or debit note is raised"
  }

  def mount(_params, _session, socket) do
    {:ok,
     socket
     |> assign(:page_title, "Webhooks")
     |> assign(:active_nav, :settings)
     |> assign(:event_descriptions, @event_descriptions)
     |> assign(:new_secret, nil)
     |> assign(:selected, nil)
     |> assign(:deliveries, [])
     |> assign_form(%{"events" => ["invoice.created", "invoice.paid"]})
     |> load_endpoints()}
  end

  defp load_endpoints(socket), do: assign(socket, :endpoints, Webhooks.list_endpoints())

  defp assign_form(socket, params, changeset \\ nil) do
    changeset =
      changeset ||
        Webhooks.change_endpoint(%Endpoint{}, %{
          "url" => params["url"],
          "description" => params["description"],
          "events" => events(params)
        })

    socket
    |> assign(:form, to_form(changeset, as: :endpoint))
    |> assign(:selected_events, events(params))
  end

  # The form sends an empty entry first so that unticking every box still
  # submits the field; it is not an event.
  defp events(params), do: params |> Map.get("events") |> List.wrap() |> Enum.reject(&(&1 == ""))

  def handle_event("validate", %{"endpoint" => params}, socket) do
    {:noreply, assign_form(socket, params)}
  end

  def handle_event("create", %{"endpoint" => params}, socket) do
    attrs = Map.put(params, "events", events(params))

    case Webhooks.create_endpoint(attrs, owner(socket)) do
      {:ok, endpoint, secret} ->
        {:noreply,
         socket
         |> assign(:new_secret, %{url: endpoint.url, secret: secret})
         |> assign_form(%{"events" => ["invoice.created", "invoice.paid"]})
         |> load_endpoints()}

      {:error, changeset} ->
        {:noreply, assign_form(socket, params, Map.put(changeset, :action, :insert))}
    end
  end

  # The secret leaves the assigns as soon as the owner says they have it, so it
  # is not re-sent with every later render of this page.
  def handle_event("dismiss_secret", _params, socket) do
    {:noreply, assign(socket, :new_secret, nil)}
  end

  def handle_event("rotate", %{"id" => id}, socket) do
    with_endpoint(socket, id, fn endpoint ->
      {:ok, endpoint, secret} = Webhooks.rotate_secret(endpoint, owner(socket))

      socket
      |> assign(:new_secret, %{url: endpoint.url, secret: secret, rotated?: true})
      |> load_endpoints()
    end)
  end

  def handle_event("toggle", %{"id" => id}, socket) do
    with_endpoint(socket, id, fn endpoint ->
      {:ok, _endpoint} = Webhooks.set_enabled(endpoint, not endpoint.enabled, owner(socket))
      load_endpoints(socket)
    end)
  end

  def handle_event("test", %{"id" => id}, socket) do
    with_endpoint(socket, id, fn endpoint ->
      {:ok, _delivery} = Webhooks.send_test(endpoint)

      socket
      |> put_flash(:info, "Test event queued for #{endpoint.url}.")
      |> show_deliveries(endpoint)
    end)
  end

  def handle_event("delete", %{"id" => id}, socket) do
    with_endpoint(socket, id, fn endpoint ->
      {:ok, _endpoint} = Webhooks.delete_endpoint(endpoint, owner(socket))

      socket
      |> put_flash(:info, "#{endpoint.url} removed.")
      |> assign(:selected, nil)
      |> assign(:deliveries, [])
      |> load_endpoints()
    end)
  end

  def handle_event("show_deliveries", %{"id" => id}, socket) do
    with_endpoint(socket, id, &show_deliveries(socket, &1))
  end

  def handle_event("resend", %{"id" => id}, socket) do
    case socket.assigns.selected && Webhooks.get_delivery(socket.assigns.selected, id) do
      nil ->
        {:noreply, socket}

      delivery ->
        {:ok, _delivery} = Webhooks.resend(delivery)

        {:noreply,
         socket
         |> put_flash(:info, "#{delivery.event_type} queued again under the same event id.")
         |> show_deliveries(socket.assigns.selected)}
    end
  end

  def handle_event("refresh", _params, socket) do
    socket = load_endpoints(socket)

    case socket.assigns.selected && Webhooks.get_endpoint(socket.assigns.selected.id) do
      nil -> {:noreply, socket}
      endpoint -> {:noreply, show_deliveries(socket, endpoint)}
    end
  end

  defp with_endpoint(socket, id, fun) do
    case Webhooks.get_endpoint(id) do
      nil -> {:noreply, load_endpoints(socket)}
      endpoint -> {:noreply, fun.(endpoint)}
    end
  end

  defp show_deliveries(socket, endpoint) do
    socket
    |> assign(:selected, endpoint)
    |> assign(:deliveries, Webhooks.list_deliveries(endpoint))
  end

  defp owner(socket), do: socket.assigns.current_scope.user

  defp delivery_tone("succeeded"), do: "text-success"
  defp delivery_tone("pending"), do: "text-warning"
  defp delivery_tone("failed"), do: "text-error"
  defp delivery_tone(_cancelled), do: "text-base-content/50"

  def render(assigns) do
    ~H"""
    <Layouts.app
      flash={@flash}
      current_scope={@current_scope}
      active_nav={@active_nav}
      active_sub={:webhooks}
    >
      <.header>
        Webhooks
        <:subtitle>
          Send this business's events to your own systems. Each event carries an id and the
          record it is about; fetch the details through the API. Every delivery is signed with
          the endpoint's secret.
        </:subtitle>
        <:actions>
          <button
            id="refresh-webhooks"
            type="button"
            phx-click="refresh"
            class={secondary_button_class()}
          >
            <.icon name="hero-arrow-path" class="size-4" /> Refresh
          </button>
        </:actions>
      </.header>

      <.card :if={@new_secret} id="new-webhook-secret" class="mb-4 border-success/40 bg-success/5">
        <div class="flex items-start gap-3">
          <.icon name="hero-key" class="mt-0.5 size-5 shrink-0 text-success" />
          <div class="min-w-0 flex-1">
            <h3 class="text-sm font-semibold">Copy the signing secret for {@new_secret.url} now</h3>
            <p class="mb-3 text-xs text-base-content/60">
              This is the only time it is shown.
              <span :if={@new_secret[:rotated?]}>
                The previous secret keeps signing alongside it for 24 hours, so you can update your
                receiver without missing events.
              </span>
            </p>

            <div class="flex flex-col gap-2 sm:flex-row sm:items-center">
              <code
                id="new-webhook-secret-value"
                class="block min-w-0 flex-1 select-all break-all rounded-field border border-base-300 bg-base-100 px-3 py-2 font-mono text-xs"
              >
                {@new_secret.secret}
              </code>

              <button
                id="dismiss-webhook-secret"
                type="button"
                phx-click="dismiss_secret"
                class={action_button_class()}
              >
                I have saved it
              </button>
            </div>
          </div>
        </div>
      </.card>

      <.card class="mb-4">
        <h3 class="mb-1 text-sm font-semibold">Add an endpoint</h3>
        <p class="mb-3 text-xs text-base-content/60">
          An https URL on your server. It must answer with a 2xx within ten seconds; anything else
          is retried for about a day. Ten failed deliveries in a row switch the endpoint off.
        </p>

        <.form for={@form} id="webhook-form" phx-change="validate" phx-submit="create">
          <div class="grid gap-3 sm:grid-cols-[1fr_16rem]">
            <.input
              field={@form[:url]}
              type="url"
              label="URL"
              placeholder="https://erp.example.com/hooks/quantumbilling"
              required
            />
            <.input
              field={@form[:description]}
              type="text"
              label="Note (optional)"
              placeholder="e.g. Accounting sync"
              maxlength="120"
            />
          </div>

          <fieldset id="webhook-events" class="mt-2">
            <legend class="mb-2 text-xs font-medium text-base-content/70">Events</legend>
            <input type="hidden" name="endpoint[events][]" value="" />
            <div class="grid gap-2 sm:grid-cols-2">
              <label
                :for={type <- Webhooks.event_types()}
                for={"event-#{type}"}
                class={[
                  "flex cursor-pointer items-start gap-2 rounded-field border px-3 py-2 transition-colors",
                  if(type in @selected_events,
                    do: "border-primary/50 bg-primary/5",
                    else: "border-base-300 hover:border-base-content/30"
                  )
                ]}
              >
                <input
                  type="checkbox"
                  id={"event-#{type}"}
                  name="endpoint[events][]"
                  value={type}
                  checked={type in @selected_events}
                  class="checkbox checkbox-sm mt-0.5"
                />
                <span class="min-w-0">
                  <span class="block font-mono text-xs">{type}</span>
                  <span class="block text-xs text-base-content/60">{@event_descriptions[type]}</span>
                </span>
              </label>
            </div>
            <p
              :for={{message, _opts} <- Keyword.get_values(@form.errors, :events)}
              :if={@form.source.action}
              class="mt-1 text-xs text-error"
            >
              {message}
            </p>
          </fieldset>

          <div class="mt-4 flex justify-end">
            <button id="create-webhook" type="submit" class={action_button_class()}>
              <.icon name="hero-plus" class="size-4" /> Add endpoint
            </button>
          </div>
        </.form>
      </.card>

      <.card class="mb-4">
        <h3 class="mb-3 text-sm font-semibold">Endpoints</h3>

        <.empty_state
          :if={@endpoints == []}
          icon="hero-signal"
          title="No endpoints"
          description="Endpoints you add appear here, with what happened to their deliveries."
        />

        <ul :if={@endpoints != []} id="webhook-endpoints" class="divide-y divide-base-300">
          <li :for={endpoint <- @endpoints} id={"endpoint-#{endpoint.id}"} class="py-3">
            <div class="flex flex-col gap-2 sm:flex-row sm:items-start sm:justify-between">
              <div class="min-w-0">
                <p class="truncate font-mono text-xs">{endpoint.url}</p>
                <p :if={endpoint.description} class="text-xs text-base-content/60">
                  {endpoint.description}
                </p>
                <div class="mt-1 flex flex-wrap items-center gap-1">
                  <.status_badge status={if endpoint.enabled, do: "Active", else: "Inactive"} />
                  <span
                    :if={endpoint.format == "legacy"}
                    class="rounded-field bg-warning/15 px-1.5 py-0.5 text-[11px] text-warning"
                    title="Carried over from the old single webhook setting. Rotating the secret moves it to the current format."
                  >
                    legacy format
                  </span>
                  <span
                    :for={type <- endpoint.events}
                    class="rounded-field bg-base-200 px-1.5 py-0.5 font-mono text-[11px]"
                  >
                    {type}
                  </span>
                </div>
                <p
                  :if={not endpoint.enabled and endpoint.disabled_reason}
                  class="mt-1 text-xs text-error"
                >
                  Off: {endpoint.disabled_reason}
                </p>
              </div>

              <div class="flex shrink-0 flex-wrap gap-1">
                <button
                  id={"show-deliveries-#{endpoint.id}"}
                  type="button"
                  phx-click="show_deliveries"
                  phx-value-id={endpoint.id}
                  class="btn btn-xs btn-ghost"
                >
                  Deliveries
                </button>
                <button
                  id={"test-endpoint-#{endpoint.id}"}
                  type="button"
                  phx-click="test"
                  phx-value-id={endpoint.id}
                  class="btn btn-xs btn-ghost"
                >
                  Send test
                </button>
                <button
                  id={"toggle-endpoint-#{endpoint.id}"}
                  type="button"
                  phx-click="toggle"
                  phx-value-id={endpoint.id}
                  class="btn btn-xs btn-ghost"
                >
                  {if endpoint.enabled, do: "Switch off", else: "Switch on"}
                </button>
                <button
                  id={"rotate-endpoint-#{endpoint.id}"}
                  type="button"
                  phx-click="rotate"
                  phx-value-id={endpoint.id}
                  data-confirm="Issue a new signing secret? The current one keeps working for 24 hours."
                  class="btn btn-xs btn-ghost"
                >
                  Rotate secret
                </button>
                <button
                  id={"delete-endpoint-#{endpoint.id}"}
                  type="button"
                  phx-click="delete"
                  phx-value-id={endpoint.id}
                  data-confirm={"Remove #{endpoint.url} and its delivery log?"}
                  class="btn btn-xs btn-ghost text-error"
                >
                  Remove
                </button>
              </div>
            </div>
          </li>
        </ul>
      </.card>

      <.card :if={@selected} id="webhook-deliveries">
        <h3 class="mb-1 text-sm font-semibold">Deliveries to {@selected.url}</h3>
        <p class="mb-3 text-xs text-base-content/60">
          The latest 50. Resending sends the same event id and body, so a receiver that already has
          it can tell.
        </p>

        <.empty_state
          :if={@deliveries == []}
          icon="hero-inbox"
          title="Nothing sent yet"
          description="Deliveries appear here as events happen."
        />

        <div :if={@deliveries != []} class="overflow-x-auto">
          <table class="table table-fixed">
            <thead>
              <tr class={table_head_class()}>
                <th class="w-48">Event</th>
                <th class="w-56">Event id</th>
                <th class="w-24">State</th>
                <th class="w-20">Tries</th>
                <th>Last answer</th>
                <th class="w-32">When</th>
                <th class="w-20 text-right"></th>
              </tr>
            </thead>
            <tbody>
              <tr
                :for={delivery <- @deliveries}
                id={"delivery-#{delivery.id}"}
                class={table_row_class()}
              >
                <td class="truncate font-mono text-xs">{delivery.event_type}</td>
                <td class="truncate font-mono text-[11px] text-base-content/60">
                  {delivery.event_id}
                </td>
                <td class={["text-xs font-medium", delivery_tone(delivery.status)]}>
                  {delivery.status}
                </td>
                <td class="text-xs">{delivery.attempts}</td>
                <td class="truncate text-xs text-base-content/60">
                  {delivery.last_status_code && "HTTP #{delivery.last_status_code}"}
                  {delivery.last_error}
                </td>
                <td class="text-xs text-base-content/60">{relative_time(delivery.inserted_at)}</td>
                <td class="text-right">
                  <button
                    :if={delivery.status in ["failed", "cancelled", "succeeded"]}
                    id={"resend-delivery-#{delivery.id}"}
                    type="button"
                    phx-click="resend"
                    phx-value-id={delivery.id}
                    class="btn btn-xs btn-ghost"
                  >
                    Resend
                  </button>
                </td>
              </tr>
            </tbody>
          </table>
        </div>
      </.card>
    </Layouts.app>
    """
  end
end
