defmodule QuantumBilling.EInvoice.Payload do
  @moduledoc """
  Builds the INV-01 element tree for an invoice, as XML.

  INV-01 names and nesting map one-to-one to the GST JSON schema, so a GSP
  integration is a mechanical transform. This is not a registered e-invoice
  (no IRN or signed QR). Values are `{:characters, _}` so `Saxy` escapes them.
  """

  alias QuantumBilling.GST
  alias QuantumBilling.EInvoice
  alias QuantumBilling.Invoices.Invoice
  alias QuantumBilling.Invoices.InvoiceItem
  alias QuantumBilling.Money
  alias QuantumBilling.Settings.Organization

  @version "1.1"

  # Bill of Supply and Export Invoice are absent on purpose; see EInvoice.validate/2.
  @types %{
    "Tax Invoice" => "INV",
    "Export Invoice" => "INV",
    "Credit Note" => "CRN",
    "Debit Note" => "DBN"
  }

  @doc "The document type code for an invoice type, or `nil` if it has none."
  def type_code(invoice_type), do: Map.get(@types, invoice_type)

  @doc "Every invoice type that can be exported."
  def exportable_types, do: Map.keys(@types)

  @doc "The `Saxy` simple-form tree for `invoice`. Assumes `EInvoice.validate/2` has passed."
  def build(%Invoice{} = invoice, %Organization{} = organization) do
    {"Invoice", [],
     [
       comment(invoice),
       element("Version", @version),
       tran_details(invoice),
       doc_details(invoice),
       seller_details(organization),
       buyer_details(invoice),
       item_list(invoice),
       value_details(invoice),
       export_details(invoice)
     ]
     |> compact()}
  end

  defp comment(invoice) do
    {:comment,
     "\n  GST e-invoice (INV-01) data for #{invoice.invoice_number}, rendered as XML.\n" <>
       "  This is NOT a registered e-invoice: it carries no IRN and no signed QR,\n" <>
       "  because only the Invoice Registration Portal can issue those. Generated by\n" <>
       "  QuantumBilling for record-keeping and for handing to a GSP or an accountant.\n"}
  end

  defp tran_details(invoice) do
    {"TranDtls", [],
     [
       element("TaxSch", "GST"),
       element("SupTyp", supply_type(invoice)),
       # Reverse charge (CGST Act s. 9(3), IGST Act s. 5(3)): the recipient pays the tax.
       element("RegRev", if(Invoice.gst_reverse_charge?(invoice), do: "Y", else: "N"))
     ]}
  end

  defp supply_type(invoice), do: EInvoice.supply_type(invoice)

  defp doc_details(invoice) do
    {"DocDtls", [],
     [
       element("Typ", type_code(invoice.invoice_type)),
       element("No", invoice.invoice_number),
       element("Dt", date(invoice.invoice_date))
     ]}
  end

  defp seller_details(organization) do
    {"SellerDtls", [],
     [
       element("Gstin", organization.gstin),
       element("LglNm", organization.company_name),
       maybe("TrdNm", organization.trade_name),
       element("Addr1", first_line(organization.address)),
       maybe("Addr2", rest_lines(organization.address)),
       element("Loc", organization.city),
       element("Pin", organization.pincode),
       element("Stcd", GST.state_code(organization.state))
     ]
     |> compact()}
  end

  # From the invoice's snapshot, not the client record.
  defp buyer_details(invoice) do
    {"BuyerDtls", [],
     [
       maybe("Gstin", if(EInvoice.export?(invoice), do: "URP", else: invoice.client_gstin)),
       element("LglNm", invoice.client_name),
       element(
         "Pos",
         if(EInvoice.export?(invoice), do: "96", else: GST.state_code(invoice.place_of_supply))
       ),
       element("Addr1", first_line(invoice.client_billing_address)),
       maybe("Addr2", rest_lines(invoice.client_billing_address)),
       element("Loc", invoice.client_city),
       element("Pin", if(EInvoice.export?(invoice), do: "999999", else: invoice.client_pincode)),
       element(
         "Stcd",
         if(EInvoice.export?(invoice),
           do: "96",
           else: GST.state_code(invoice.client_state) || GST.state_code(invoice.place_of_supply)
         )
       )
     ]
     |> compact()}
  end

  defp export_details(invoice) do
    if EInvoice.export?(invoice) do
      {"ExpDtls", [],
       [
         element("ForCur", invoice.currency),
         element("CntCode", invoice.client_country),
         element("RefClm", if(invoice.export_type == "EXPORT_WITH_PAY", do: "Y", else: "N"))
       ]}
    end
  end

  defp item_list(invoice) do
    intra_state? = not EInvoice.export?(invoice) and Invoice.intra_state?(invoice)

    items =
      invoice.items
      |> Enum.with_index(1)
      |> Enum.map(fn {item, index} ->
        item(item, index, intra_state?, Invoice.gst_reverse_charge?(invoice), invoice)
      end)

    {"ItemList", [], items}
  end

  # With RegRev "Y" the IRP lets the item value leave out the tax, which the
  # recipient pays; the tax amounts are still reported.
  defp item(%InvoiceItem{} = item, index, intra_state?, reverse_charge?, invoice) do
    amount = InvoiceItem.amount(item)
    tax = if invoice.export_type == "EXPORT_WITHOUT_PAY", do: 0, else: InvoiceItem.tax(item)
    {cgst, sgst, igst} = split(tax, intra_state?)

    {"Item", [],
     [
       element("SlNo", Integer.to_string(index)),
       element("PrdDesc", item.description),
       # SAC codes (services) begin with 99.
       element("IsServc", if(service?(item.hsn_sac), do: "Y", else: "N")),
       element("HsnCd", item.hsn_sac),
       element("Qty", quantity(item.quantity)),
       element("Unit", unit_code(item.unit)),
       element("UnitPrice", decimal(item.rate, invoice)),
       element("TotAmt", decimal(amount, invoice)),
       element("AssAmt", decimal(amount, invoice)),
       element("GstRt", percent(item.tax_rate)),
       element("CgstAmt", decimal(cgst, invoice)),
       element("SgstAmt", decimal(sgst, invoice)),
       element("IgstAmt", decimal(igst, invoice)),
       element(
         "TotItemVal",
         decimal(if(reverse_charge?, do: amount, else: amount + tax), invoice)
       )
     ]}
  end

  defp value_details(invoice) do
    {"ValDtls", [],
     [
       element("AssVal", decimal(invoice.taxable_value, invoice)),
       element("CgstVal", decimal(reported_tax(invoice, :cgst), invoice)),
       element("SgstVal", decimal(reported_tax(invoice, :sgst), invoice)),
       element("IgstVal", decimal(reported_tax(invoice, :igst), invoice)),
       element("CesVal", decimal(reported_tax(invoice, :cess), invoice)),
       element("RndOffAmt", decimal(invoice.round_off, invoice)),
       element("TotInvVal", decimal(invoice.grand_total, invoice))
     ]}
  end

  @doc """
  The tax an e-invoice reports for a head (`:cgst`, `:sgst`, `:igst`,
  `:cess`): what was charged, or on a reverse-charge invoice what the
  recipient pays. `TotInvVal` stays the invoice total, which leaves it out.
  """
  def reported_tax(%Invoice{} = invoice, :cgst),
    do: (invoice.cgst_amount || 0) + (invoice.rc_cgst_amount || 0)

  def reported_tax(%Invoice{} = invoice, :sgst),
    do: (invoice.sgst_amount || 0) + (invoice.rc_sgst_amount || 0)

  def reported_tax(%Invoice{} = invoice, :igst),
    do: (invoice.igst_amount || 0) + (invoice.rc_igst_amount || 0)

  def reported_tax(%Invoice{} = invoice, :cess),
    do: (invoice.cess_amount || 0) + (invoice.rc_cess_amount || 0)

  defp split(tax, true), do: {div(tax, 2), tax - div(tax, 2), 0}
  defp split(tax, false), do: {0, 0, tax}

  defp service?(hsn) when is_binary(hsn), do: String.starts_with?(hsn, "99")
  defp service?(_hsn), do: false

  @units %{
    "Nos" => "NOS",
    "Kg" => "KGS",
    "Ltr" => "LTR",
    "Mtr" => "MTR",
    "Box" => "BOX",
    "Set" => "SET",
    "Pcs" => "PCS",
    "Hrs" => "HRS"
  }

  defp unit_code(unit), do: Map.get(@units, unit, "OTH")

  # dd/mm/yyyy, as INV-01 specifies.
  defp date(%Date{} = date), do: Calendar.strftime(date, "%d/%m/%Y")
  defp date(_other), do: ""

  # Paise in, rupees with two decimals out.
  defp decimal(nil), do: "0.00"
  defp decimal(paise) when is_integer(paise), do: Money.to_input(paise)
  defp decimal(amount, invoice), do: amount |> EInvoice.inr_paise(invoice) |> decimal()

  # A GST rate is a plain percentage, not money.
  defp percent(nil), do: "0.00"
  defp percent(rate) when is_integer(rate), do: :erlang.float_to_binary(rate * 1.0, decimals: 2)

  # Three places, as INV-01 allows.
  defp quantity(quantity) do
    (Money.quantity(quantity) || Decimal.new(0))
    |> Decimal.round(3)
    |> Decimal.to_string(:normal)
  end

  defp first_line(nil), do: ""

  defp first_line(address) do
    address |> String.split("\n", parts: 2) |> List.first() |> String.trim()
  end

  defp rest_lines(nil), do: nil

  defp rest_lines(address) do
    case String.split(address, "\n", parts: 2) do
      [_first, rest] -> rest |> String.replace("\n", ", ") |> String.trim()
      _only_one -> nil
    end
  end

  defp element(name, value), do: {name, [], [{:characters, to_string(value || "")}]}

  defp maybe(_name, blank) when blank in [nil, ""], do: nil
  defp maybe(name, value), do: element(name, value)

  defp compact(children), do: Enum.reject(children, &is_nil/1)
end
